#!/usr/bin/env python3
"""Generate `docs/STATUS.md` -- the status board -- and the pair table in
`docs/handoff/README.md`, from the record; `--check` fails on drift.

THE BOARD IS GENERATED, OR IT LIES (0019-ruling.md; WORKING_AGREEMENT.md,
"A STATUS BOARD IS GENERATED, OR IT LIES"). Nobody owns it: this script
does, and the gate's docs lane runs `--check` beside `Docs-Index`. Built on
Patrick's word of 2026-10-10 ("build it, the mailbox is the record now") to
the read-back at 0232-report.md.

THE SOURCE IS ONE LINE PER LANDING, IN THE MAILBOX. A report that records a
merge carries, directly under its title, one fixed-format line:

    **Landed:** PR #77 · 53d676d · 2026-10-10 · AMBER · checked: the dialog (his word)

five fields separated by ` · ` (a middle dot with a space each side): the PR,
the merge commit's short hash, the merge date, the tier (`GREEN`, `AMBER`,
`RED`, or `—` when the record does not say), and free text saying what the
merge rested on. A PR that closed without merging carries

    **Not landed:** PR #59 · — · 2026-09-13 · closed · superseded by #60

`docs/handoff/0000-landings.md` holds the lines for merges no report
records -- everything before the mailbox existed -- so the board starts at
PR #1. The reader is strict: a malformed line is MALFORMED, not skipped,
because a permissive reader would silently reinterpret the shape it exists
to pin (the `defects_index.py` / `progress_index.py` contract).

TWO CHECKS, both offline:
  * `STATUS.md` and the README's pair table equal a regeneration;
  * every `PR #N` named in a first-parent commit subject on `main` has a
    `**Landed:**` or `**Not landed:**` line -- the landing commit and the
    report that records it are written minutes apart by the same hand, and
    this closes the gap between them where 0217 sec3 and 0219 sec2 record
    it opening before.

    python tools/status_index.py            # rewrite STATUS.md and the pair table
    python tools/status_index.py --check     # fail if either would change,
                                             # or a landing commit has no line
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HANDOFF = ROOT / "docs" / "handoff"
DEFECTS = ROOT / "docs" / "defects"
ROADMAP = ROOT / "docs" / "ROADMAP.md"
STATUS = ROOT / "docs" / "STATUS.md"
README = HANDOFF / "README.md"

SEP = " · "
LANDED_RE = re.compile(
    r"^\*\*(Landed|Not landed):\*\* PR #(\d+) · ([0-9a-f]{7,40}|—) · (\d{4}-\d{2}-\d{2}) · "
    r"(GREEN|AMBER|RED|—|closed) · (.+?)\s*$")
PR_IN_SUBJECT = re.compile(r"\bPR #(\d+)\b")
PAIRS_BEGIN = "<!-- PAIRS:BEGIN -- generated by tools/status_index.py; do not hand-edit -->"
PAIRS_END = "<!-- PAIRS:END -->"


# -- the record -------------------------------------------------------------
def handoff_files():
    return sorted(p for p in HANDOFF.glob("[0-9][0-9][0-9][0-9]-*.md"))


def landings():
    """Every landing line in the mailbox: {pr: record}. Raises ValueError on a
    malformed line or a PR landed twice."""
    out = {}
    for path in handoff_files():
        fenced = False
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if line.startswith("```"):          # an example in a code block is not a landing
                fenced = not fenced
                continue
            if fenced or (not line.startswith("**Landed:**")
                          and not line.startswith("**Not landed:**")):
                continue
            m = LANDED_RE.match(line)
            if not m:
                raise ValueError(
                    f"{path.name}:{n}: a landing line must read "
                    "`**Landed:** PR #N · <sha7> · YYYY-MM-DD · GREEN|AMBER|RED|— · <what it rested on>` "
                    f"(or `**Not landed:** PR #N · — · YYYY-MM-DD · closed · <why>`), got {line!r}")
            kind, pr, sha, date, tier, rest = m.groups()
            pr = int(pr)
            if pr in out:
                raise ValueError(f"{path.name}:{n}: PR #{pr} already landed at {out[pr]['file']}")
            if kind == "Landed" and (sha == "—" or tier == "closed"):
                raise ValueError(f"{path.name}:{n}: a Landed line needs a commit and a tier")
            if kind == "Not landed" and (sha != "—" or tier != "closed"):
                raise ValueError(f"{path.name}:{n}: a Not landed line is `— · <date> · closed`")
            out[pr] = {"pr": pr, "landed": kind == "Landed", "sha": sha, "date": date,
                       "tier": tier, "rest": rest, "file": path.name, "line": n}
    return out


def defect_counts():
    opened = closed = 0
    for path in sorted(DEFECTS.glob("[0-9]*.md")):
        head = path.read_text(encoding="utf-8").split("\n", 40)[:40]
        state = next((ln.split(":", 1)[1].strip() for ln in head if ln.startswith("state:")), None)
        if state == "open":
            opened += 1
        elif state == "closed":
            closed += 1
    return opened, closed


def roadmap_red():
    """The RED table of ROADMAP.md sec3: (item, what it needs) per row."""
    text = ROADMAP.read_text(encoding="utf-8")
    m = re.search(r"^### RED[^\n]*\n(.*?)(?=^##|\Z)", text, re.S | re.M)
    if not m:
        return []
    rows = []
    for ln in m.group(1).splitlines():
        if ln.startswith("| ") and not ln.startswith("| item") and not ln.startswith("|---"):
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            if len(cells) >= 2:
                rows.append((cells[0], cells[1]))
    return rows


def pair_rows():
    """One line per mailbox file: its number, kind and title clause."""
    rows = []
    for path in handoff_files():
        first = path.read_text(encoding="utf-8").split("\n", 1)[0].strip()
        title = re.sub(r"^#\s*\d{4}\s*[—–-]+\s*", "", first)
        rows.append((path.name, title))
    return rows


def main_subject_prs():
    """PR numbers named in first-parent commit subjects on HEAD, or None when
    git is unavailable."""
    try:
        out = subprocess.run(["git", "log", "--first-parent", "--format=%s"], cwd=ROOT,
                             capture_output=True, text=True, encoding="utf-8",
                             errors="replace", check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    return {int(n) for n in PR_IN_SUBJECT.findall(out)}


# -- rendering ----------------------------------------------------------------
def _pr_link(n):
    return f"[#{n}](https://github.com/pjm4github/FloorPlanner/pull/{n})"


def render_status(land, defects, red):
    opened, closed = defects
    landed = [r for r in land.values() if r["landed"]]
    not_landed = [r for r in land.values() if not r["landed"]]
    lines = [
        "# Status board",
        "",
        "<!-- GENERATED by tools/status_index.py — do not hand-edit. -->",
        "<!-- `python tools/status_index.py` rewrites it; `--check` fails on drift. -->",
        "",
        "**Generated from the record** — one `**Landed:**` line per merge in "
        "[`handoff/`](handoff/), the defect register's front matter, and "
        "[`ROADMAP.md`](ROADMAP.md) §3's RED table. This file says whether a thing "
        "is DONE; [`SESSION_SNAPSHOT.md`](SESSION_SNAPSHOT.md) keeps the order and "
        "the why ([`handoff/0019-ruling.md`](handoff/0019-ruling.md) §4). A box that "
        "is not derived from the record is not on this board.",
        "",
        f"**{len(landed)} landed, {len(not_landed)} closed unmerged; "
        f"{opened} defects open, {closed} closed.**",
        "",
        "## Landed",
        "",
        "| PR | date | commit | tier | what it rested on | record |",
        "|---|---|---|---|---|---|",
    ]
    for r in sorted(landed, key=lambda r: -r["pr"]):
        rec = f"[`{r['file'][:4]}`](handoff/{r['file']})"
        lines.append(f"| {_pr_link(r['pr'])} | {r['date']} | `{r['sha']}` | {r['tier']} | "
                     f"{r['rest']} | {rec} |")
    if not_landed:
        lines += ["", "## Closed without merging", "",
                  "| PR | date | why | record |", "|---|---|---|---|"]
        for r in sorted(not_landed, key=lambda r: -r["pr"]):
            lines.append(f"| {_pr_link(r['pr'])} | {r['date']} | {r['rest']} | "
                         f"[`{r['file'][:4]}`](handoff/{r['file']}) |")
    lines += ["", "## Named, not landed", "",
              "From [`ROADMAP.md`](ROADMAP.md) §3's RED table — each waits on its own ruling.",
              "", "| item | what it needs |", "|---|---|"]
    for item, needs in red:
        lines.append(f"| {item} | {needs} |")
    lines += ["", "## Defects", "",
              f"{opened} open, {closed} closed — the register is "
              "[`defects/INDEX.md`](defects/INDEX.md), generated by `tools/defects_index.py`.",
              ""]
    return "\n".join(lines)


def render_pairs(rows):
    body = [PAIRS_BEGIN, "", "| pair | subject |", "|---|---|"]
    for name, title in rows:
        body.append(f"| [`{name}`](./{name}) | {title} |")
    body += ["", PAIRS_END]
    return "\n".join(body)


def readme_with_pairs(text, rows):
    """`text` with the generated region replaced (or appended after the pair
    table's heading when the markers are absent)."""
    block = render_pairs(rows)
    if PAIRS_BEGIN in text and PAIRS_END in text:
        a = text.index(PAIRS_BEGIN)
        b = text.index(PAIRS_END) + len(PAIRS_END)
        return text[:a] + block + text[b:]
    raise ValueError("docs/handoff/README.md has no PAIRS:BEGIN/PAIRS:END markers")


# -- entry ------------------------------------------------------------------------
def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        land = landings()
        want_status = render_status(land, defect_counts(), roadmap_red())
        readme = README.read_text(encoding="utf-8")
        want_readme = readme_with_pairs(readme, pair_rows())
    except ValueError as e:
        print(f"Docs-Status: MALFORMED -- {e}")
        return 1
    have_status = STATUS.read_text(encoding="utf-8") if STATUS.exists() else None
    # the landing cross-check: a landing commit on main with no line
    prs = main_subject_prs()
    missing = sorted(prs - set(land)) if prs is not None else []
    if a.check:
        rc = 0
        if have_status != want_status:
            print("Docs-Status: STATUS.md DIFFERS from a regeneration "
                  "(run `python tools/status_index.py`)")
            rc = 1
        if readme != want_readme:
            print("Docs-Status: handoff/README.md's pair table DIFFERS from a "
                  "regeneration (run `python tools/status_index.py`)")
            rc = 1
        if missing:
            print("Docs-Status: RED -- a commit subject on main names "
                  f"PR #{', #'.join(map(str, missing))} and no handoff report carries a "
                  "`**Landed:**` (or `**Not landed:**`) line for it")
            rc = 1
        if rc == 0:
            print(f"Docs-Status: STATUS.md and the pair table match a regeneration "
                  f"({len(land)} landings, {len(pair_rows())} pairs; every PR on main has its line)")
        return rc
    STATUS.write_text(want_status, encoding="utf-8", newline="\n")
    README.write_text(want_readme, encoding="utf-8", newline="\n")
    print(f"Docs-Status: wrote docs/STATUS.md ({len(land)} landings) and the pair table")
    if missing:
        print("Docs-Status: WARNING -- no landing line for PR "
              f"#{', #'.join(map(str, missing))} named on main")
    return 0


if __name__ == "__main__":
    sys.exit(main())
