"""The status board is generated, or it lies (0019-ruling.md; built at 0232
on Patrick's word, "build it, the mailbox is the record now").

`tools/status_index.py` reads one `**Landed:**` line per merge from the
mailbox, the defect register's front matter and ROADMAP.md sec3's RED
table, writes `docs/STATUS.md` and the pair table in `docs/handoff/README.md`,
and `--check` fails on drift, on a malformed line, and on a landing commit
whose PR has no line. These tests hold each of those, on the real record
and on a synthetic one.
"""
import importlib.util
import pathlib
import re
import subprocess
import sys

import pytest

pytestmark = pytest.mark.io

ROOT = pathlib.Path(__file__).resolve().parent.parent


def _load():
    path = ROOT / "tools" / "status_index.py"
    spec = importlib.util.spec_from_file_location("status_index_under_test", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def si():
    return _load()


# --------------------------------------------------------------------------
# the real record
# --------------------------------------------------------------------------
def test_the_board_and_the_pair_table_match_a_regeneration(si, capsys):
    assert si.main(["--check"]) == 0
    out = capsys.readouterr().out
    assert "match a regeneration" in out and "every PR on main has its line" in out


def test_every_merged_pr_from_1_to_the_latest_has_a_landing_line(si):
    """The backfill's receipt: PRs #1..#77 each have a line, #59 the only
    one closed unmerged; no number is missing from the run."""
    land = si.landings()
    nums = sorted(land)
    assert nums[0] == 1 and nums == list(range(1, nums[-1] + 1)), "a gap in the run"
    assert nums[-1] >= 77
    assert [n for n, r in land.items() if not r["landed"]] == [59]
    for r in land.values():
        if r["landed"]:
            assert re.fullmatch(r"[0-9a-f]{7}", r["sha"]), r


def test_every_landed_commit_is_a_commit_on_main(si):
    """No invented hashes: each landed commit is reachable from HEAD."""
    land = si.landings()
    reach = subprocess.run(["git", "rev-list", "--first-parent", "HEAD"], cwd=ROOT,
                           capture_output=True, text=True).stdout
    assert reach, "git history unavailable"
    for r in land.values():
        if r["landed"]:
            assert re.search(rf"^{r['sha']}", reach, re.M), f"PR #{r['pr']}: {r['sha']} is not on main"


def test_every_merge_report_carries_its_line_and_nothing_else_does_twice(si):
    """A report whose title records a merge has a landing line; the 0000
    stub holds every line no report does; no PR is landed twice (the
    reader refuses it, so this is the positive control that it reads them
    all)."""
    land = si.landings()
    for path in si.handoff_files():
        title = path.read_text(encoding="utf-8").split("\n", 1)[0]
        if re.search(r"PR #\d+ merged|merged on his word|'s merge recorded", title):
            assert any(r["file"] == path.name for r in land.values()), path.name
    stub = [r for r in land.values() if r["file"].startswith("0000-")]
    assert 30 < len(stub) < 60
    assert not any(r["pr"] >= 64 for r in stub), "every merge since 0194 has its own report"
    reports = {r["pr"] for r in land.values() if not r["file"].startswith("0000-")}
    assert not reports & {r["pr"] for r in stub}


def test_the_pair_table_lists_every_mailbox_file(si):
    readme = (ROOT / "docs" / "handoff" / "README.md").read_text(encoding="utf-8")
    region = readme[readme.index(si.PAIRS_BEGIN):readme.index(si.PAIRS_END)]
    listed = set(re.findall(r"\[`(\d{4}-[^`]+\.md)`\]", region))
    assert listed == {p.name for p in si.handoff_files()}
    assert "0232-report.md" in listed and "0116-ruling.md" in listed


def test_the_board_renders_the_roadmaps_red_table_and_the_defect_counts(si):
    text = (ROOT / "docs" / "STATUS.md").read_text(encoding="utf-8")
    assert "## Named, not landed" in text and "P5.1" in text and "P6.3" in text
    opened, closed = si.defect_counts()
    assert opened + closed >= 86 and f"{opened} open, {closed} closed" in text
    assert "GENERATED by tools/status_index.py" in text


