def _sandbox(si, tmp_path, monkeypatch, handoff_lines, readme=None):
    h = tmp_path / "docs" / "handoff"
    d = tmp_path / "docs" / "defects"
    h.mkdir(parents=True, exist_ok=True)
    d.mkdir(exist_ok=True)
    (tmp_path / "docs" / "ROADMAP.md").write_text(
        "## 3. The work\n\n### RED — do not start\n\n| item | what it needs |\n|---|---|\n"
        "| **X** | a ruling |\n\n## 4. next\n", encoding="utf-8")
    (d / "0001-a.md").write_text("---\nid: 1\nstate: open\n---\n# D1\n", encoding="utf-8")
    (d / "0002-b.md").write_text("---\nid: 2\nstate: closed\n---\n# D2\n", encoding="utf-8")
    for name, body in handoff_lines.items():
        (h / name).write_text(body, encoding="utf-8")
    (h / "README.md").write_text(readme or f"intro\n\n{si.PAIRS_BEGIN}\n{si.PAIRS_END}\n", encoding="utf-8")
    monkeypatch.setattr(si, "HANDOFF", h)
    monkeypatch.setattr(si, "DEFECTS", d)
    monkeypatch.setattr(si, "ROADMAP", tmp_path / "docs" / "ROADMAP.md")
    monkeypatch.setattr(si, "STATUS", tmp_path / "docs" / "STATUS.md")
    monkeypatch.setattr(si, "README", h / "README.md")


GOOD = "# 0001 — report: PR #1 merged\n\n**Landed:** PR #1 · abc1234 · 2026-01-02 · GREEN · on green CI\n\nbody\n"


def test_a_synthetic_record_generates_and_then_checks_clean(si, tmp_path, monkeypatch, capsys):
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": GOOD})
    monkeypatch.setattr(si, "main_subject_prs", lambda: {1})
    assert si.main([]) == 0
    text = si.STATUS.read_text(encoding="utf-8")
    assert "| [#1](https://github.com/pjm4github/FloorPlanner/pull/1) | 2026-01-02 | `abc1234` | GREEN | on green CI |" in text
    assert "**1 landed, 0 closed unmerged; 1 defects open, 1 closed.**" in text
    assert "| **X** | a ruling |" in text
    assert si.main(["--check"]) == 0


def test_a_hand_edit_to_the_board_is_red(si, tmp_path, monkeypatch, capsys):
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": GOOD})
    monkeypatch.setattr(si, "main_subject_prs", lambda: {1})
    si.main([])
    si.STATUS.write_text(si.STATUS.read_text(encoding="utf-8").replace("GREEN", "AMBER"), encoding="utf-8")
    assert si.main(["--check"]) == 1
    assert "STATUS.md DIFFERS" in capsys.readouterr().out


def test_a_landing_commit_with_no_line_is_red(si, tmp_path, monkeypatch, capsys):
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": GOOD})
    monkeypatch.setattr(si, "main_subject_prs", lambda: {1, 2})
    si.main([])
    assert si.main(["--check"]) == 1
    assert "PR #2" in capsys.readouterr().out


@pytest.mark.parametrize("line, why", [
    ("**Landed:** PR #1 · abc1234 · 2026-01-02 · GREEN", "a field short"),
    ("**Landed:** PR #1 · abc1234 · 2026-1-2 · GREEN · x", "a date not ISO"),
    ("**Landed:** PR #1 · abc1234 · 2026-01-02 · BLUE · x", "a tier not in the set"),
    ("**Landed:** PR #1 · — · 2026-01-02 · GREEN · x", "a Landed line with no commit"),
    ("**Not landed:** PR #1 · abc1234 · 2026-01-02 · closed · x", "a Not landed line with a commit"),
    ("**Landed:** PR #1 - abc1234 - 2026-01-02 - GREEN - x", "the wrong separator"),
])
def test_a_malformed_line_is_malformed_not_skipped(si, tmp_path, monkeypatch, capsys, line, why):
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": f"# 0001 — report\n\n{line}\n"})
    assert si.main(["--check"]) == 1, why
    assert "MALFORMED" in capsys.readouterr().out


def test_a_pr_landed_twice_is_malformed_and_an_example_in_a_code_block_is_not_a_landing(
        si, tmp_path, monkeypatch, capsys):
    twice = GOOD + "\n**Landed:** PR #1 · abc1234 · 2026-01-02 · GREEN · again\n"
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": twice})
    assert si.main(["--check"]) == 1 and "already landed" in capsys.readouterr().out
    fenced = GOOD + "\n```\n**Landed:** PR #1 · abc1234 · 2026-01-02 · GREEN · an example\n```\n"
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": fenced})
    monkeypatch.setattr(si, "main_subject_prs", lambda: {1})
    assert si.main([]) == 0 and len(si.landings()) == 1


def test_the_readme_without_markers_is_malformed(si, tmp_path, monkeypatch, capsys):
    _sandbox(si, tmp_path, monkeypatch, {"0001-report.md": GOOD}, readme="no markers here\n")
    assert si.main(["--check"]) == 1
    assert "PAIRS:BEGIN" in capsys.readouterr().out
